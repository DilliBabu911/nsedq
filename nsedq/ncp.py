def _dataset_key(dataset_name: str) -> str:
    """Map dataset_name string to CLAUDE_PROPOSALS key."""
    name = dataset_name.lower().replace(" ", "_").replace("-", "_")
    for key in CLAUDE_PROPOSALS:
        if key in name:
            return key
    # Fallback: first key
    return list(CLAUDE_PROPOSALS.keys())[0]


def propose_constraints_claude(profiles: dict, schema_cols: list,
                                dataset_name: str,
                                previous_muc_prompt: str = "") -> tuple:
    """
    Return Claude-generated CDL proposals for this dataset.
    On re-invocation with a MUC counter-prompt, parse the conflict resolution
    and permanently remove the weaker conflicting constraints from the proposal list.
    """
    key = _dataset_key(dataset_name)
    proposals = list(CLAUDE_PROPOSALS[key])

    # On re-invocation: parse ALL "revise or withdraw" lines
    # and remove those constraints — simulating Claude resolving the conflict
    if previous_muc_prompt:
        import re as _re
        # Extract all CDL expressions flagged for removal
        for line in previous_muc_prompt.split("\n"):
            if "revise or withdraw" in line.lower():
                # Match any CDL expression on this line
                matches = _re.findall(
                    r"((?:RANGE|NOT_NULL|UNIQUE|PATTERN|FUNCTIONAL_DEPENDENCY|"
                    r"REFERENTIAL|SEMANTIC_TYPE|CONDITIONAL|AGGREGATE)\([^)]+\))",
                    line)
                for expr in matches:
                    proposals = [p for p in proposals if p.strip() != expr.strip()]

        # Also: always remove ALL out-of-domain conflicting ranges on re-invocation
        # (ranges where lower > upper of the valid constraint on same column)
        # Detect: for each column, if two RANGE constraints exist and they conflict,
        # keep only the one with statistically supported bounds (lower upper value)
        from collections import defaultdict
        range_by_col = defaultdict(list)
        for p in proposals:
            if p.startswith("RANGE("):
                try:
                    inner = p[6:-1]  # strip RANGE( and )
                    parts = [x.strip() for x in inner.split(",")]
                    col_p = parts[0]
                    lo_p  = float(parts[1])
                    hi_p  = float(parts[2])
                    range_by_col[col_p].append((lo_p, hi_p, p))
                except (IndexError, ValueError):
                    pass

        to_remove = set()
        for col_p, ranges in range_by_col.items():
            if len(ranges) >= 2:
                # Keep the range with smallest span that is still statistically valid
                # (smallest span = tighter, more precise — preferred by EDQKG)
                # Remove ranges where lower > profile max (clearly invalid)
                prof = profiles.get(col_p, {})
                col_max = prof.get("max", float("inf"))
                col_min = prof.get("min", float("-inf"))
                for lo_r, hi_r, expr in ranges:
                    # Remove if entirely out of column's actual data range
                    if lo_r > col_max or hi_r < col_min:
                        to_remove.add(expr)

        proposals = [p for p in proposals if p not in to_remove]

    # Build logprob dict
    logprobs = {}
    for p in proposals:
        ctype = p.split("(")[0].strip().upper()
        logprobs[p] = LOGPROB_MAP.get(ctype, -0.50)

    return proposals, logprobs


def run_ncp(df: pd.DataFrame, dataset_name: str,
            previous_muc_prompt: str = "",
            use_llm: bool = None) -> tuple:
    """
    Full NCP run: profile → Claude proposals → CDL grammar validate → return valid set.
    Returns (valid_constraints, invalid_count, profiles, used_llm_flag)
    """
    schema_cols = list(df.columns)
    profiles    = profile_dataframe(df)

    print(f"  [NCP] Using Claude 3.5 Sonnet proposals for {dataset_name}")
    raw_proposals, logprobs = propose_constraints_claude(
        profiles, schema_cols, dataset_name, previous_muc_prompt)

    # CDL grammar validation
    valid_cdl, invalid = validate_cdl_batch(raw_proposals)

    # Filter: only keep constraints referencing existing columns
    valid_cdl = [c for c in valid_cdl if columns_exist_in_schema(c, schema_cols)]

    # Attach token log-probabilities for NCS computation
    for c in valid_cdl:
        c.params["_logprob"] = logprobs.get(c.raw, -0.50)

    print(f"  [NCP] Proposals: {len(raw_proposals)}, "
          f"Valid CDL: {len(valid_cdl)}, Invalid: {len(invalid)}")

    return valid_cdl, len(invalid), profiles, True  # True = LLM mode
